DEFAULT_PERSONA = "normal"


def get_persona(key):
    return PERSONAS.get(key) or PERSONAS[DEFAULT_PERSONA]


def full_system_prompt(key, normal_override=None):
    """人设 + 底线，作为 system 消息（稳定，便于前缀缓存）。

    normal_override：config.yaml 的 `reply.persona`，用来覆盖「普通观众」
    这一套的风格段。只对 normal 生效——切到 assistant / humorous 等其它
    人设时不能再叠一段"像老观众一样说话"，否则两套风格互相打架。
    IDENTITY 与 IMMUTABLE 永远在最外层，任何配置都覆盖不了。
    """
    key = key if key in PERSONAS else DEFAULT_PERSONA
    prompt = PERSONAS[key]["prompt"]
    if key == DEFAULT_PERSONA and (normal_override or "").strip():
        prompt = normal_override.strip()
    return IDENTITY + "\n\n" + prompt + "\n\n" + IMMUTABLE


def list_personas():
    return [(k, v["name"], v["desc"]) for k, v in PERSONAS.items()]
